    try:
        path = _report_module().write_report(args.output, summary, sw)
    except ValueError as exc:
        raise UsageError(str(exc)) from exc
    extra = f" with sweep of {sweep_id}" if sw is not None else ""
    _out(f"wrote {path} (run {run_id}{extra})")
    return EXIT_OK


