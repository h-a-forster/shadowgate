def _cmd_audit(args: argparse.Namespace) -> int:
    if args.run_pending:
        return _audit_run_pending(args)
    if args.config:
        raise UsageError("-c/--config is only used with --run-pending")
    ledger_path = Path(args.ledger) if args.ledger else DEFAULT_LEDGER
    with _open_ledger(ledger_path) as ledger:
        run_id = _resolve_run(ledger, args.run_id)
        tolerance = args.tolerance if args.tolerance is not None else _run_tolerance(ledger, run_id)
        summary = _summarize(list(ledger.decisions(run_id)), tolerance)
    return _emit_audit(args, summary)


def _emit_audit(args: argparse.Namespace, summary: AuditSummary) -> int:
    if args.json:
        _print_json(summary)
    else:
        _out(_report_module().render_text(summary).rstrip("\n"))
    if args.fail_on_breach and summary.status == "breach":
        _err(
            f"shadowgate: audit breach: skipped-case {summary.status_metric or 'error'} "
            f"exceeds tolerance {_pct(summary.tolerance)}"
        )
        return EXIT_BREACH
    return EXIT_OK


def _audit_run_pending(args: argparse.Namespace) -> int:
    from .config import load_config
    from .runner import run_pending_audits

    if not args.config:
        raise UsageError("--run-pending needs -c/--config to build the audit tier")
    cfg = load_config(args.config)
    ledger_path = Path(args.ledger) if args.ledger else cfg.settings.ledger_path
    with _open_ledger(ledger_path) as ledger:
        run_id = _resolve_run(ledger, args.run_id)
        decisions = list(ledger.decisions(run_id))
        # Simulated backends need the task list; the ledger stores every task.
        cascade, settings = cfg.build(tasks=[d.task for d in decisions])
        progress = _Progress("audits", enabled=not args.json)
        try:
            stats = run_pending_audits(
                cascade,
                ledger,
                run_id=run_id,
                workers=args.workers or settings.workers,
                max_cost_usd=args.max_cost if args.max_cost is not None else settings.max_cost_usd,
                progress=progress,
            )
        finally:
            progress.close()
        _err(f"pending audits for {run_id}: {stats.summary_line()}")
        tolerance = args.tolerance
        if tolerance is None:
            tolerance = settings.tolerance
        if tolerance is None:
            tolerance = _run_tolerance(ledger, run_id)
        summary = _summarize(list(ledger.decisions(run_id)), tolerance)
    code = _emit_audit(args, summary)
    if stats.stopped:
        return _stop_exit_code(stats.stopped)
    return code


