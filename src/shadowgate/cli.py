def _cmd_demo(args: argparse.Namespace) -> int:
    from .datasets import arithmetic, save_tasks
    from .runner import run

    if args.n < 1:
        raise UsageError("--n must be >= 1")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    tasks = arithmetic(args.n, seed=args.seed)
    save_tasks(tasks, out / "tasks.jsonl")
    (out / "shadowgate.toml").write_text(
        DEMO_CONFIG.replace("seed = 0\n", f"seed = {args.seed}\n", 1),
        encoding="utf-8",
        newline="\n",
    )
    cfg = _demo_config(args.seed)
    cascade, settings = cfg.build(tasks=tasks)
    raw_tiers = cfg.raw["tiers"]
    backends = cfg.raw["backends"]
    _out(
        f"shadowgate demo: {len(tasks)} simulated arithmetic tasks (seed {args.seed}); "
        f"fast tier skill {backends['fast']['skill']:g} (overconfident), "
        f"slow tier skill {backends['slow']['skill']:g}"
    )
    ledger_path = out / "ledger.sqlite"
    base = f"demo-n{args.n}-s{args.seed}"
    eval_id, serve_id = f"{base}-eval", f"{base}-serve"
    snapshot = cfg.snapshot()
    with _open_ledger(ledger_path, create=True) as ledger:
        results: dict[str, RunStats] = {}
        for run_id, mode in ((eval_id, "eval"), (serve_id, "serve")):
            progress = _Progress(f"{mode} run", enabled=not args.quiet)
            try:
                stats = run(
                    cascade,
                    tasks,
                    ledger,
                    run_id=run_id,
                    mode=mode,
                    workers=settings.workers,
                    config_snapshot=snapshot,
                    progress=progress,
                )
            finally:
                progress.close()
            results[mode] = stats
            _out(f"  {mode:<5} run {run_id}: {stats.summary_line()}")
            if stats.stopped:
                return _stop_exit_code(stats.stopped)
        serve_decisions = list(ledger.decisions(serve_id))
        summary = _summarize(serve_decisions, settings.tolerance)
        sweep_result = _sweep(list(ledger.decisions(eval_id)), seed=args.seed)

    _out("")
    _print_demo_summary(summary, sweep_result, float(raw_tiers[0]["threshold"]))
    _out("")
    _out(_demo_conclusion(summary, serve_decisions, raw_tiers[0]["name"]))
    report = _report_module()
    html_path = report.write_report(out / "report.html", summary, sweep_result)
    md_path = report.write_report(out / "report.md", summary, sweep_result)
    _out("")
    _out(f"report: {html_path} (also {md_path.name})")
    _out(f"explore: shadowgate audit --ledger {ledger_path} --run-id {serve_id}")
    _out(f"         shadowgate sweep --ledger {ledger_path} --run-id {eval_id}")
    _out(f"next:    shadowgate calibrate --ledger {ledger_path} --run-id {eval_id}")
    if args.open:
        import webbrowser

        webbrowser.open(Path(html_path).resolve().as_uri())
    return EXIT_OK


def _demo_conclusion(summary: AuditSummary, decisions: Sequence[Decision], tier: str) -> str:
    """One plain sentence: reported confidence on kept answers vs the audited disagreement."""
    kept = [
        float(d.attempts[0].confidence.score)
        for d in decisions
        if d.error is None
        and not d.escalated
        and d.attempts
        and d.attempts[0].confidence is not None
        and d.attempts[0].confidence.score is not None
    ]
    ref = summary.reference_tier or "the final tier"
    dis = summary.disagreement
    if not kept or dis is None or dis.value is None:
        return f"The {tier} tier kept no audited answers, so there is nothing to compare yet."
    conf = sum(kept) / len(kept)
    ci = ""
    if dis.lo is not None and dis.hi is not None:
        ci = f" ({100 * summary.level:.0f}% CI {100 * dis.lo:.0f}-{100 * dis.hi:.0f}%)"
    text = (
        f"The {tier} tier reports {100 * conf:.0f}% mean confidence on the answers it keeps; "
        f"the audit estimates {100 * dis.value:.0f}% of them disagree with the {ref} tier{ci}"
    )
    implied = 1.0 - conf
    if dis.lo is not None and dis.lo > implied:
        text += f", more than the {100 * implied:.0f}% its confidence implies"
    elif dis.value > implied:
        text += (
            f", more than the {100 * implied:.0f}% its confidence implies "
            "(though the interval includes it)"
        )
    return text + "."


def _print_demo_summary(summary: AuditSummary, sw: SweepResult, threshold: float) -> None:
    ref = summary.reference_tier or (summary.tiers[-1] if summary.tiers else "reference")
    _out(f"Serve mode: confidence threshold {threshold:.2f}, stratified shadow audits")
    _out(f"  escalation rate         {_est(summary.escalation_rate)}")
    _out(
        f"  kept by fast tier       {summary.n_skipped} decisions, "
        f"{summary.n_audited} shadow-audited by {ref!r}"
    )
    _out(f"  disagreement on kept    {_est(summary.disagreement)} (weighted by 1/pi)")
    if summary.skipped_error is not None:
        _out(f"  error on kept           {_est(summary.skipped_error)} (vs references)")
    if summary.served_accuracy is not None:
        _out(f"  served accuracy         {_est(summary.served_accuracy)}")
    _out(f"  cost per task           {_usd(summary.cost_per_task)}")
    if summary.est_savings is not None:
        _out(f"  est. savings vs {ref:<7} {_est(summary.est_savings)}")
    status = summary.status
    if summary.tolerance is not None:
        status += f" (tolerance {_pct(summary.tolerance)}"
        if summary.audits_to_resolve:
            status += f"; ~{summary.audits_to_resolve} more audits to resolve"
        status += ")"
    _out(f"  audit status            {status}")
    _out("")
    _out("Eval mode: every tier on every task, threshold sweep")
    for name, p in sw.baselines.items():
        _out(f"  {name:<22}  accuracy {_est(p.accuracy):<26} cost/task {_usd(p.cost_per_task)}")
    rec = sw.recommendation
    if rec is None:
        _out("  no recommendation: " + (sw.notes[-1] if sw.notes else "no point met the target"))
        return
    last = sw.baselines.get(f"only:{sw.tiers[-1]}")
    p = rec.holdout or rec.point
    where = f"held-out n={rec.n_holdout}" if rec.holdout is not None else "in-sample"
    line = (
        f"  recommended threshold   {_thr(rec.thresholds)} -> accuracy {_est(p.accuracy)}, "
        f"cost/task {_usd(p.cost_per_task)} ({where})"
    )
    _out(line)
    if rec.holdout is not None and "caution" in rec.note:
        _out("  (held-out accuracy is below the selection target; see the report's caveats)")
    if last is not None and last.cost_per_task and p.cost_per_task is not None:
        change = _pct(p.cost_per_task / last.cost_per_task - 1)
        _out(f"  cost vs {sw.tiers[-1] + '-only':<15} {change}")


