def _cmd_run(args: argparse.Namespace) -> int:
    from .config import load_config
    from .datasets import load_tasks
    from .runner import run

    if args.limit is not None and args.limit < 0:
        raise UsageError("--limit must be >= 0")
    if args.workers is not None and args.workers < 1:
        raise UsageError("--workers must be >= 1")
    if args.max_cost is not None and args.max_cost < 0:
        raise UsageError("--max-cost must be >= 0")
    cfg = load_config(args.config)
    tasks = load_tasks(args.tasks, limit=args.limit)
    if not tasks:
        raise DatasetError(f"{args.tasks}: no tasks")
    cascade, settings = cfg.build(tasks=tasks)
    ledger_path = Path(args.ledger) if args.ledger else settings.ledger_path
    workers = args.workers or settings.workers
    max_cost = args.max_cost if args.max_cost is not None else settings.max_cost_usd

    with _open_ledger(ledger_path, create=True) as ledger:
        existing = {r.run_id: r for r in ledger.runs()}
        if args.run_id:
            run_id = args.run_id
            prev = existing.get(run_id)
            if prev is not None and prev.mode != args.mode:
                raise UsageError(
                    f"run {run_id!r} exists in {ledger_path} with mode {prev.mode!r}; "
                    f"pass --mode {prev.mode} to resume it or choose another --run-id"
                )
        else:
            stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S")
            base = f"{settings.name}-{args.mode}-{stamp}"
            run_id, k = base, 2
            while run_id in existing:  # never resume a run implicitly
                run_id, k = f"{base}-{k}", k + 1
        resuming = run_id in existing and not args.no_resume
        if not args.quiet:
            verb = "resuming" if resuming else "starting"
            _out(
                f"{verb} run {run_id}  (mode {args.mode}, {len(tasks)} tasks, "
                f"{workers} workers, ledger {ledger_path})"
            )
        progress = _Progress("run", enabled=not args.quiet)
        try:
            stats = run(
                cascade,
                tasks,
                ledger,
                run_id=run_id,
                mode=args.mode,
                workers=workers,
                max_cost_usd=max_cost,
                resume=not args.no_resume,
                config_snapshot=cfg.snapshot(),
                progress=progress,
            )
        finally:
            progress.close()
        pending = sum(1 for _ in ledger.pending_audits(run_id))

    _out(f"run {run_id}: {stats.summary_line()}")
    resume_cmd = f"shadowgate run -c {args.config} -t {args.tasks} --run-id {run_id}"
    if args.mode != "serve":
        resume_cmd += f" --mode {args.mode}"
    if args.ledger:
        resume_cmd += f" --ledger {args.ledger}"
    ledger_opt = f" --ledger {args.ledger}" if args.ledger else ""
    if stats.failed and not stats.stopped:
        _err(f"shadowgate: warning: {stats.failed} task(s) failed; see the ledger for details")
    if stats.stopped:
        reason = {
            "budget": f"spending cap of ${max_cost} reached",
            "failures": "too many consecutive failures",
            "interrupted": "interrupted",
        }.get(stats.stopped, stats.stopped)
        _err(f"shadowgate: stopped early ({reason}); resume with:")
        _err(f"  {resume_cmd}")
    elif not args.quiet:
        if pending:
            _out(
                f"{pending} deferred audit(s) pending: shadowgate audit --run-pending "
                f"-c {args.config} --run-id {run_id}{ledger_opt}"
            )
        nxt = "sweep" if args.mode == "eval" else "audit"
        _out(f"next: shadowgate {nxt} --run-id {run_id}{ledger_opt}")
    return _stop_exit_code(stats.stopped)


