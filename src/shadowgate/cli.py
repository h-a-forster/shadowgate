def _cmd_init(args: argparse.Namespace) -> int:
    from .datasets import arithmetic, save_tasks

    target = Path(args.dir)
    config_path = target / "shadowgate.toml"
    tasks_path = target / "tasks.jsonl"
    existing = [p for p in (config_path, tasks_path) if p.exists()]
    if existing and not args.force:
        names = ", ".join(str(p) for p in existing)
        raise UsageError(f"refusing to overwrite {names} (pass --force to replace)")
    target.mkdir(parents=True, exist_ok=True)
    config_path.write_text(STARTER_CONFIG, encoding="utf-8", newline="\n")
    save_tasks(arithmetic(20, seed=0), tasks_path)
    _out(f"wrote {config_path}")
    _out(f"wrote {tasks_path} (20 arithmetic tasks)")
    _out("")
    _out("next:")
    _out(f"  shadowgate run -c {config_path} -t {tasks_path}")
    _out("  shadowgate audit")
    return EXIT_OK


