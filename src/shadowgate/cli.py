def _render_sweep(sw: SweepResult) -> str:
    lines = [
        f"Threshold sweep: {sw.n} decisions, tiers {' -> '.join(sw.tiers)}, truth: {sw.truth}",
        f"  {len(sw.points)} operating points, {len(sw.frontier)} on the Pareto frontier",
        "",
        "Baselines",
    ]
    lines += [_point_line(name, p) for name, p in sw.baselines.items()]
    lines += ["", "Pareto frontier (cheapest first)"]
    frontier = [sw.points[i] for i in sw.frontier]
    if len(frontier) > 12:
        step = math.ceil(len(frontier) / 12)
        frontier = frontier[::step] + ([frontier[-1]] if (len(frontier) - 1) % step else [])
    lines += [_point_line(f"threshold {_thr(p.thresholds)}", p) for p in frontier]
    rec = sw.recommendation
    lines += ["", "Recommendation"]
    if rec is None:
        lines.append("  none: no operating point meets the objective")
    else:
        lines.append(f"  objective {rec.objective}: threshold {_thr(rec.thresholds)}")
        lines.append(_point_line(f"selection (n={rec.n_selection})", rec.point))
        if rec.holdout is not None:
            lines.append(_point_line(f"held-out (n={rec.n_holdout})", rec.holdout))
        if rec.delta_vs_best is not None and rec.best_single_tier:
            d = rec.delta_vs_best
            lines.append(
                f"  accuracy vs {rec.best_single_tier}-only: "
                f"{_signed_pts(d.value)} [{_signed_pts(d.lo)}, {_signed_pts(d.hi)}] points"
            )
        lines += textwrap.wrap(rec.note, 96, initial_indent="  ", subsequent_indent="  ")
    if sw.calibration:
        lines += ["", "Confidence calibration (non-final tiers)"]
        for tier, c in sw.calibration.items():
            lines.append(
                f"  {tier:<12} n={c.n}  ECE {_num(c.ece)}  Brier {_num(c.brier)}  "
                f"AUROC {_num(c.auroc)}  AURC {_num(c.aurc)}"
            )
    if sw.notes:
        lines += ["", "Notes"] + [f"  - {n}" for n in sw.notes]
    return "\n".join(lines)


def _signed_pts(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:+.1f}"


def _num(x: float | None) -> str:
    return "n/a" if x is None or not math.isfinite(x) else f"{x:.3f}"


