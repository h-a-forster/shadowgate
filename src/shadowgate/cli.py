def _error_code(exc: ShadowgateError) -> int:
    # A missing ledger or unknown run is a UsageError; other LedgerErrors are runtime errors.
    if isinstance(exc, (UsageError, ConfigError, DatasetError)):
        return EXIT_USAGE
    return EXIT_RUNTIME


def main(argv: Sequence[str] | None = None) -> int:
    """Run the CLI; returns the process exit code (see :data:`EXIT_CODES`)."""
    _setup_console()
    parser = build_parser()
    try:
        args = parser.parse_args(list(argv) if argv is not None else None)
    except SystemExit as exc:  # --help, --version, usage errors
        code = exc.code
        return code if isinstance(code, int) else (0 if code is None else EXIT_USAGE)
    _setup_logging(args.verbose)
    debug = os.environ.get("SHADOWGATE_DEBUG") == "1"
    try:
        return int(args.func(args))
    except KeyboardInterrupt:
        _err("shadowgate: interrupted")
        return EXIT_INTERRUPTED
    except ShadowgateError as exc:
        if debug:
            traceback.print_exc()
        _err(f"shadowgate: error: {exc}")
        return _error_code(exc)
    except OSError as exc:
        if debug:
            traceback.print_exc()
        _err(f"shadowgate: error: {exc}")
        return EXIT_RUNTIME
    except Exception as exc:
        if debug:
            traceback.print_exc()
        _err(f"shadowgate: error: unexpected {type(exc).__name__}: {exc}")
        _err("shadowgate: set SHADOWGATE_DEBUG=1 for a traceback")
        return EXIT_RUNTIME
    finally:
        sys.stdout.flush()


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
